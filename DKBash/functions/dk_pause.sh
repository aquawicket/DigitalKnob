# dk_pause(pause_msg)
#
#	Pause execution and wait for keypress to continue
#
dk_pause() {
	dk_debugFunc 0 1

	[ -z "${1-}" ] && pause_msg="Press enter to continue..." || pause_msg="${1}"
	#read -rp 'Press enter to continue...'; # key; echo ${key}
	echo "${pause_msg}"
	read -rp ''
}



